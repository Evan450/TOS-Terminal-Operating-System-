#!/usr/bin/env python3
"""Write MANUAL.md's linked contents list from its own headings.

WHY THIS EXISTS. MANUAL.md is three thousand lines in two books, and the
only map was a paragraph describing the books -- an outside review of the
docs (2026-10-03) asked for a linked contents list. A hand-kept one would
drift the way the README's file list did, so this generates it: every book
and part, every chapter (`## N.`), every section (`### N.M`), linked by the
anchor GitHub gives each heading. It lives between two markers in the
manual and nothing else in the file is touched.

    python build/make_manual_toc.py           rewrite the contents list
    python build/make_manual_toc.py --check   exit 1 if it is stale

`python tos.py check` runs the --check, and build/test_manual_toc.py keeps
it in the suite.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

DEV = Path(__file__).resolve().parent.parent
MANUAL = DEV / "MANUAL.md"
BEGIN = "<!-- contents: generated by build/make_manual_toc.py; do not edit by hand -->"
END = "<!-- /contents -->"


def slug(text: str) -> str:
    """GitHub's heading anchor: lowercase, drop punctuation, spaces to '-'."""
    s = text.strip().lower()
    s = re.sub(r"[^\w\- ]", "", s)
    return s.replace(" ", "-")


def contents(md: str) -> str:
    lines, seen = [], {}
    in_code = False
    for raw in md.splitlines():
        if raw.startswith("```"):
            in_code = not in_code
            continue
        if in_code:
            continue
        m = re.match(r"^(#{1,3}) (.+?)\s*$", raw)
        if not m:
            continue
        level, title = len(m.group(1)), m.group(2)
        base = slug(title)
        n = seen.get(base, 0)
        seen[base] = n + 1
        anchor = base if n == 0 else f"{base}-{n}"
        if level == 1:
            if title.startswith(("BOOK", "Part")):
                lines.append(f"\n**{title}**\n")
            continue
        if level == 2 and re.match(r"(\d+\.|Appendix)", title):
            lines.append(f"- [{title}](#{anchor})")
        elif level == 3 and re.match(r"\d+\.\d+ ", title):
            lines.append(f"  - [{title}](#{anchor})")
    body = "\n".join(lines).strip("\n")
    return f"{BEGIN}\n\n## Contents\n\n{body}\n\n{END}"


def splice(md: str, block: str) -> str:
    if BEGIN in md and END in md:
        i, j = md.index(BEGIN), md.index(END) + len(END)
        return md[:i] + block + md[j:]
    # First run: after "How this Manual is organized", before Book One.
    k = md.index("\n# BOOK ONE")
    return md[:k] + "\n" + block + "\n\n---\n" + md[k:]


def main(argv: list[str]) -> int:
    raw = MANUAL.read_bytes().decode("utf-8")
    crlf = "\r\n" in raw
    md = raw.replace("\r\n", "\n")
    # Generate from the manual WITHOUT its old contents block, so a heading
    # inside the block (## Contents) never lists itself.
    if BEGIN in md and END in md:
        i, j = md.index(BEGIN), md.index(END) + len(END)
        source = md[:i] + md[j:]
    else:
        source = md
    new = splice(md, contents(source))
    if "--check" in argv:
        if new != md:
            print("MANUAL.md's contents list is stale: run  python build/make_manual_toc.py")
            return 1
        return 0
    if new != md:
        out = new.replace("\n", "\r\n") if crlf else new
        tmp = MANUAL.with_suffix(".md.tmp")
        tmp.write_bytes(out.encode("utf-8"))
        if tmp.stat().st_size < 100_000:
            raise SystemExit("refusing to write a truncated MANUAL.md")
        tmp.replace(MANUAL)
    entries = contents(source).count("](#")
    print(f"MANUAL.md contents list: {entries} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
