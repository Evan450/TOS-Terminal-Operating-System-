"""MANUAL.md's contents list is current, and every link in it lands.

The list is generated by build/make_manual_toc.py from the manual's own
headings. This fails when a heading changed and the list was not
regenerated, and when a generated link names an anchor no heading has
(GitHub drops punctuation and keeps the hyphens a dropped "&" leaves).

Run: pytest TOS-Dev/build/test_manual_toc.py
"""

from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("make_manual_toc", HERE / "make_manual_toc.py")
toc = importlib.util.module_from_spec(spec)
sys.modules["make_manual_toc"] = toc
spec.loader.exec_module(toc)

MANUAL = (HERE.parent / "MANUAL.md").read_text(encoding="utf-8")


def test_the_contents_list_is_current():
    assert toc.main(["--check"]) == 0, "run: python build/make_manual_toc.py"


def test_every_contents_link_names_a_heading():
    block = MANUAL[MANUAL.index(toc.BEGIN):MANUAL.index(toc.END)]
    anchors = re.findall(r"\]\(#([^)]+)\)", block)
    assert len(anchors) > 60
    heads = {toc.slug(m.group(1)) for m in re.finditer(r"^#{1,6} (.+?)\s*$", MANUAL, re.M)}
    missing = [a for a in anchors if a not in heads]
    assert not missing, missing


def test_slugs_follow_githubs_rules():
    assert toc.slug("1.2 Installing TOS") == "12-installing-tos"
    assert toc.slug("3. Logging In, Users & Tiers") == "3-logging-in-users--tiers"
    assert toc.slug("5.4 Unmanaged (raw) drives — TBFS") == "54-unmanaged-raw-drives--tbfs"
    assert toc.slug("2.1 The boot spectrum (`/etc/boot.cfg`)") == "21-the-boot-spectrum-etcbootcfg"
