#!/usr/bin/env python3
"""Generate docs/API.md, the kernel API reference, from the code itself.

MANUAL.md is the operator's book and stays written by hand. What was missing
is a reference for the kernel API that cannot silently disagree with the
code, so this one is generated: every public function in tos/kernel/
(`function mod.name(...)` at the top level), its signature, and the `---`
comment block directly above it. `--!` and `--` comments are not API text
and are left out.

A function's doc block may carry a tier mark:

    --- @tier admin        refuses callers below ADMIN
    --- @tier root         refuses callers below ROOT

and the mark is CHECKED, both ways (build/test_apiref.py): a public function
whose body calls one of the kernel's admin gates must say so, and a function
that says so must call one. Fuchas annotates permissions and never checks
them; an annotation nobody checks is a comment that has not gone stale yet.

    python build/make_apiref.py           write docs/API.md
    python build/make_apiref.py --check   exit 1 if it is stale or a tier
                                          mark disagrees with its gate
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KERNEL = ROOT / "tos" / "kernel"
OUT = ROOT / "docs" / "API.md"

DEF = re.compile(r"^function ([A-Za-z_]\w*)\.(\w+)\((.*?)\)(.*)$")
TIER = re.compile(r"^---\s*@tier\s+(\w+)\s*$")
# The kernel's admin gates, by the names they are defined under. A new gate
# idiom is added here, or the check cannot see it.
GATES = {
    "adminGate": "admin",          # pkg.lua
    "requireAdmin": "admin",       # securefs.lua, net/aliases.lua
    "requireAdminActor": "admin",  # net/trust.lua
}
GATE_CALL = re.compile(r"\b(" + "|".join(GATES) + r")\(")


def module_name(path: Path) -> str:
    rel = path.relative_to(ROOT / "tos").with_suffix("")
    parts = list(rel.parts)
    if parts[-1] == "init":
        parts.pop()
    return ".".join(parts)


def functions(path: Path):
    """Yield (table, name, params, doc_lines, tier, gate) per public function."""
    lines = path.read_text(encoding="utf-8").replace("\r\n", "\n").split("\n")
    i = 0
    while i < len(lines):
        m = DEF.match(lines[i])
        if not m:
            i += 1
            continue
        table, name, params, rest = m.groups()
        # One-liner (`function a.b(x) return y end`) or a block ending at a
        # top-level `end`.
        if re.search(r"\bend\s*$", rest) and rest.strip():
            body, j = rest, i
        else:
            j = i + 1
            while j < len(lines) and lines[j] != "end":
                j += 1
            body = "\n".join(lines[i + 1:j])
        doc, k = [], i - 1
        while k >= 0 and lines[k].startswith("---"):
            doc.insert(0, lines[k])
            k -= 1
        tier = None
        prose = []
        for d in doc:
            t = TIER.match(d)
            if t:
                tier = t.group(1)
            else:
                prose.append(re.sub(r"^---\s?", "", d))
        g = GATE_CALL.search(body)
        yield table, name, params, prose, tier, (g.group(1) if g else None)
        i = j + 1


def disagreements() -> list[str]:
    out = []
    for path in sorted(KERNEL.rglob("*.lua")):
        rel = path.relative_to(ROOT).as_posix()
        for table, name, _, _, tier, gate in functions(path):
            fn = f"{table}.{name}"
            if gate and tier is None:
                out.append(f"{rel}: {fn} calls {gate}() but has no `--- @tier {GATES[gate]}`")
            elif tier is not None and tier not in ("admin", "root"):
                out.append(f"{rel}: {fn} has an unknown tier '{tier}'")
            elif tier is not None and not gate:
                out.append(f"{rel}: {fn} is marked @tier {tier} but calls none of "
                           + ", ".join(sorted(GATES)))
    return out


def render() -> str:
    mods = []
    total = 0
    for path in sorted(KERNEL.rglob("*.lua")):
        fns = list(functions(path))
        if fns:
            mods.append((path, fns))
            total += len(fns)
    out = [
        "# TOS kernel API reference",
        "",
        "Generated by `build/make_apiref.py` from the code in `tos/kernel/` -- do not",
        "hand-edit; change the `---` comment above a function and regenerate. "
        f"{total} public functions in {len(mods)} modules.",
        "",
        "A function marked **admin** or **root** refuses callers below that tier.",
        "`build/test_apiref.py` checks every mark against the gate the function's",
        "body calls, and every gate against a mark.",
        "",
        "## Modules",
        "",
    ]
    for path, fns in mods:
        mod = module_name(path)
        out.append(f"- [`{mod}`](#{mod.replace('.', '')}) ({len(fns)})")
    for path, fns in mods:
        mod = module_name(path)
        rel = path.relative_to(ROOT).as_posix()
        out += ["", f"## {mod}", "", f"`{rel}`", ""]
        for table, name, params, prose, tier, _ in fns:
            mark = f" — **{tier}**" if tier else ""
            out.append(f"- `{table}.{name}({params.strip()})`{mark}")
            text = " ".join(p.strip() for p in prose if p.strip())
            if text:
                out.append(f"  {text}")
    return "\n".join(out) + "\n"


def main() -> int:
    bad = disagreements()
    for b in bad:
        print("TIER MARK: " + b, file=sys.stderr)
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print("docs/API.md is stale: run  python build/make_apiref.py", file=sys.stderr)
            return 1
        return 1 if bad else 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    tmp = OUT.with_suffix(".md.tmp")
    tmp.write_text(text, encoding="utf-8", newline="\n")
    tmp.replace(OUT)
    print(f"Wrote {OUT.relative_to(ROOT).as_posix()}: "
          f"{text.count(chr(10) + '- `')} functions"
          + (f"; {len(bad)} tier mark(s) disagree" if bad else ""))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
